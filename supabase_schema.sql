CREATE POLICY "Users can manage own profile" ON public.profiles FOR ALL USING (auth.uid() = id);
CREATE POLICY "Users can manage own races" ON public.races FOR ALL USING (auth.uid() = user_id);
CREATE POLICY "Users can manage own training plans" ON public.training_plans FOR ALL USING (auth.uid() = user_id);
CREATE POLICY "Users can manage own workouts" ON public.actual_workouts FOR ALL USING (auth.uid() = user_id);
CREATE POLICY "Users can view own metrics" ON public.activity_metrics FOR ALL USING (
    EXISTS (SELECT 1 FROM public.actual_workouts w WHERE w.id = activity_metrics.actual_workout_id AND w.user_id = auth.uid())
);
CREATE POLICY "Users can manage own chat" ON public.chat_history FOR ALL USING (auth.uid() = user_id);
CREATE POLICY "Users can view own subscription" ON public.subscriptions FOR ALL USING (auth.uid() = user_id);

-- Enable UUID extension
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- 1. PROFILES (Extended athlete bio & physiological baseline)
CREATE TABLE IF NOT EXISTS public.profiles (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    email TEXT UNIQUE NOT NULL,
    full_name TEXT,
    avatar_url TEXT,
    sport_focus TEXT DEFAULT 'running' CHECK (sport_focus IN ('running', 'cycling', 'swimming', 'triathlon')),
    fitness_level TEXT DEFAULT 'intermediate' CHECK (fitness_level IN ('beginner', 'intermediate', 'advanced', 'elite')),
    weight_kg NUMERIC(5, 2) DEFAULT 65.0,
    height_cm NUMERIC(5, 2) DEFAULT 170.0,
    resting_hr INTEGER DEFAULT 55,
    max_hr INTEGER DEFAULT 185,
    lactate_threshold_hr INTEGER DEFAULT 168,
    ftp_watts INTEGER DEFAULT 220,
    target_race_name TEXT,
    target_race_date DATE,
    weekly_mileage_target_km NUMERIC(5, 1) DEFAULT 50.0,
    unit_preference TEXT DEFAULT 'metric' CHECK (unit_preference IN ('metric', 'imperial')),
    preferred_coach_tier TEXT DEFAULT 'free' CHECK (preferred_coach_tier IN ('pemula', 'free', 'pro')),
    subscription_tier TEXT DEFAULT 'free' CHECK (subscription_tier IN ('pemula', 'free', 'pro')),
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. RACES (Target events & goal paces)
CREATE TABLE IF NOT EXISTS public.races (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    user_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    sport_type TEXT DEFAULT 'run' CHECK (sport_type IN ('run', 'cycling', 'swimming', 'triathlon')),
    distance_km NUMERIC(6, 2) NOT NULL,
    race_date DATE NOT NULL,
    location TEXT,
    target_time_seconds INTEGER,
    status TEXT DEFAULT 'upcoming' CHECK (status IN ('upcoming', 'completed', 'cancelled')),
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. TRAINING PLANS (Generated periodization cycles)
CREATE TABLE IF NOT EXISTS public.training_plans (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    user_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    race_id UUID REFERENCES public.races(id) ON DELETE SET NULL,
    name TEXT NOT NULL,
    sport_type TEXT DEFAULT 'run',
    duration_weeks INTEGER NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    is_active BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. SCHEDULED WORKOUTS (Daily prescription generated by TrainingEngine)
CREATE TABLE IF NOT EXISTS public.scheduled_workouts (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    plan_id UUID NOT NULL REFERENCES public.training_plans(id) ON DELETE CASCADE,
    workout_date DATE NOT NULL,
    workout_type TEXT NOT NULL,
    title TEXT NOT NULL,
    description TEXT,
    planned_distance_km NUMERIC(5, 2),
    planned_duration_seconds INTEGER,
    target_zone INTEGER DEFAULT 2,
    completed BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. ACTUAL WORKOUTS (Ingested from FIT, GPX, TCX, Garmin, Strava)
CREATE TABLE IF NOT EXISTS public.actual_workouts (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    user_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    source TEXT DEFAULT 'manual' CHECK (source IN ('manual', 'fit', 'gpx', 'tcx', 'garmin', 'strava', 'intervals')),
    external_id TEXT,
    title TEXT NOT NULL,
    workout_type TEXT NOT NULL,
    started_at TIMESTAMPTZ NOT NULL,
    duration_seconds INTEGER NOT NULL,
    distance_km NUMERIC(6, 2) NOT NULL,
    avg_pace_min_per_km NUMERIC(5, 2),
    elevation_gain_m NUMERIC(6, 1) DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 6. ACTIVITY METRICS (Calculated deterministically by SportsEngine)
CREATE TABLE IF NOT EXISTS public.activity_metrics (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    actual_workout_id UUID NOT NULL REFERENCES public.actual_workouts(id) ON DELETE CASCADE,
    training_load INTEGER DEFAULT 0,
    aerobic_te NUMERIC(3, 1) DEFAULT 1.0,
    anaerobic_te NUMERIC(3, 1) DEFAULT 0.0,
    avg_hr INTEGER,
    max_hr INTEGER,
    gap_min_per_km NUMERIC(5, 2),
    avg_cadence INTEGER,
    avg_power INTEGER,
    cardiac_drift_pct NUMERIC(4, 2),
    aerobic_efficiency NUMERIC(5, 3),
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 7. CHAT HISTORY (AI Coach memory with Google Gemini 3.8 Flash & OpenAI)
CREATE TABLE IF NOT EXISTS public.chat_history (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    user_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    role TEXT NOT NULL CHECK (role IN ('user', 'assistant', 'system')),
    content TEXT NOT NULL,
    provider_used TEXT,
    tier TEXT DEFAULT 'free',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 8. SUBSCRIPTIONS (Goalie Pro Plan orders & activations)
CREATE TABLE IF NOT EXISTS public.subscriptions (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    user_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    order_id TEXT UNIQUE NOT NULL,
    plan TEXT NOT NULL CHECK (plan IN ('monthly', 'annual')),
    payment_method TEXT DEFAULT 'qris',
    amount_idr INTEGER NOT NULL,
    status TEXT DEFAULT 'pending' CHECK (status IN ('pending', 'active', 'expired', 'cancelled')),
    is_active BOOLEAN DEFAULT FALSE,
    activated_at TIMESTAMPTZ,
    expires_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 9. GARMIN SESSIONS & HEALTH METRICS (Direct sync)
CREATE TABLE IF NOT EXISTS public.garmin_sessions (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    user_id UUID UNIQUE NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    email TEXT NOT NULL,
    is_active BOOLEAN DEFAULT TRUE,
    connected_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.garmin_health_metrics (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    user_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    recorded_date DATE NOT NULL,
    resting_heart_rate INTEGER,
    sleep_score INTEGER,
    hrv_status TEXT,
    body_battery INTEGER,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 10. DAILY READINESS & RECOVERY (Sleep, HRV, Soreness & Readiness Score)
CREATE TABLE IF NOT EXISTS public.daily_readiness (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    user_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    recorded_date DATE NOT NULL,
    sleep_hours NUMERIC(3, 1),
    resting_hr INTEGER,
    hrv_rmssd INTEGER,
    muscle_soreness INTEGER CHECK (muscle_soreness BETWEEN 1 AND 5),
    mental_stress INTEGER CHECK (mental_stress BETWEEN 1 AND 5),
    energy_level INTEGER CHECK (energy_level BETWEEN 1 AND 5),
    readiness_score INTEGER CHECK (readiness_score BETWEEN 0 AND 100),
    injury_risk_flag TEXT DEFAULT 'low' CHECK (injury_risk_flag IN ('low', 'moderate', 'high')),
    coach_advice TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    UNIQUE(user_id, recorded_date)
);

-- 11. ATHLETE PHYSIOLOGICAL ZONES (Karvonen HR Zones & Daniels VDOT Paces)
CREATE TABLE IF NOT EXISTS public.athlete_zones (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    user_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    resting_hr INTEGER NOT NULL,
    max_hr INTEGER NOT NULL,
    hrr INTEGER NOT NULL,
    z1_min INTEGER, z1_max INTEGER,
    z2_min INTEGER, z2_max INTEGER,
    z3_min INTEGER, z3_max INTEGER,
    z4_min INTEGER, z4_max INTEGER,
    z5_min INTEGER, z5_max INTEGER,
    vdot_score NUMERIC(4, 1),
    easy_pace_min_km NUMERIC(4, 2),
    marathon_pace_min_km NUMERIC(4, 2),
    threshold_pace_min_km NUMERIC(4, 2),
    interval_pace_min_km NUMERIC(4, 2),
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 12. WORKOUT SPLITS & INTERVAL LAPS (FIT / GPX / Manual Interval Laps)
CREATE TABLE IF NOT EXISTS public.workout_splits (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    actual_workout_id UUID NOT NULL REFERENCES public.actual_workouts(id) ON DELETE CASCADE,
    split_index INTEGER NOT NULL,
    split_distance_km NUMERIC(5, 2) NOT NULL,
    duration_seconds INTEGER NOT NULL,
    avg_pace_min_per_km NUMERIC(5, 2),
    avg_hr INTEGER,
    elevation_gain_m NUMERIC(5, 1) DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- ══════════════════════════════════════════════════════════
-- INDEXES FOR HIGH-THROUGHPUT PERFORMANCE
-- ══════════════════════════════════════════════════════════
CREATE INDEX IF NOT EXISTS idx_actual_workouts_user_started ON public.actual_workouts(user_id, started_at DESC);
CREATE INDEX IF NOT EXISTS idx_activity_metrics_workout ON public.activity_metrics(actual_workout_id);
CREATE INDEX IF NOT EXISTS idx_chat_history_user_created ON public.chat_history(user_id, created_at ASC);
CREATE INDEX IF NOT EXISTS idx_races_user_date ON public.races(user_id, race_date ASC);
CREATE INDEX IF NOT EXISTS idx_subscriptions_user ON public.subscriptions(user_id, is_active);

